if (isset($_GET['download']) && $_GET['download'] === 'sql') {
    $timestamp = date('Ymd_His');
    $filename = 'store_backup_' . $timestamp . '.sql';

    header('Content-Type: application/sql; charset=UTF-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    echo "-- ========================================================\n";
    echo "-- Store Automeation - Database Backup Archive\n";
    echo "-- Backup Date: " . date('Y-m-d H:i:s') . "\n";
    echo "-- Database Host: " . ($_ENV['STORE_DB_HOST'] ?? 'localhost') . "\n";
    echo "-- Generated by: " . ($currentUser['name'] ?? 'Admin') . " (@" . ($currentUser['username'] ?? 'admin') . ")\n";
    echo "-- ========================================================\n\n";
    echo "SET NAMES utf8mb4;\n";
    echo "SET FOREIGN_KEY_CHECKS = 0;\n\n";

    $tables = ['users', 'product', 'product_images', 'receipts', 'issues', 'audit_logs'];

    foreach ($tables as $table) {
        if (!inventory_table_exists($db, $table)) {
            continue;
        }

        echo "-- --------------------------------------------------------\n";
        echo "-- Table structure for `{$table}`\n";
        echo "-- --------------------------------------------------------\n";
        echo "DROP TABLE IF EXISTS `{$table}`;\n";

        $createStmt = $db->query('SHOW CREATE TABLE `' . $table . '`')->fetch();
        $createSql = $createStmt['Create Table'] ?? '';
        echo $createSql . ";\n\n";

        echo "-- Dumping data for `{$table}`\n";
        $rows = $db->query('SELECT * FROM `' . $table . '`')->fetchAll();
        if ($rows !== []) {
            $columnNames = array_keys($rows[0]);
            $colList = implode(', ', array_map(static fn($c) => '`' . $c . '`', $columnNames));

            foreach ($rows as $row) {
                $values = [];
                foreach ($columnNames as $col) {
                    $val = $row[$col];
                    if ($val === null) {
                        $values[] = 'NULL';
                    } elseif ($table === 'product_images' && $col === 'data') {
                        // Binary safe HEX literal for BLOB
                        $values[] = '0x' . bin2hex((string) $val);
                    } else {
                        $values[] = $db->quote((string) $val);
                    }
                }
                echo "INSERT INTO `{$table}` ({$colList}) VALUES (" . implode(', ', $values) . ");\n";
            }
        }
        echo "\n";
    }

    echo "SET FOREIGN_KEY_CHECKS = 1;\n";
    echo "-- End of backup\n";

    audit_log('backup', 'database', 'ดาวน์โหลดไฟล์สำรองฐานข้อมูล SQL (' . $filename . ')');
    exit;
}

