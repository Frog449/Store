// Helper: Format bytes
function format_bytes(float|int $bytes, int $precision = 1): string
{
    $units = ['B', 'KB', 'MB', 'GB', 'TB'];
    $bytes = max($bytes, 0);
    $pow = floor(($bytes ? log($bytes) : 0) / log(1024));
    $pow = min($pow, count($units) - 1);
    $bytes /= (1 << (10 * (int) $pow));
    return round($bytes, $precision) . ' ' . $units[$pow];
}

// Helper: Generate SQL Dump File
function server_generate_sql_dump(PDO $db, string $outputPath, array $currentUser): int
{
    $fp = fopen($outputPath, 'w');
    if (!$fp) {
        throw new RuntimeException('ไม่สามารถสร้างไฟล์สำรองข้อมูลบนเซิร์ฟเวอร์ได้');
    }

    fwrite($fp, "-- ========================================================\n");
    fwrite($fp, "-- Store Automeation - Server Database Backup Archive\n");
    fwrite($fp, "-- Backup Date: " . date('Y-m-d H:i:s') . "\n");
    fwrite($fp, "-- Server Host: " . ($_ENV['STORE_DB_HOST'] ?? 'localhost') . "\n");
    fwrite($fp, "-- Generated by: " . ($currentUser['name'] ?? 'Admin') . " (@" . ($currentUser['username'] ?? 'admin') . ")\n");
    fwrite($fp, "-- ========================================================\n\n");
    fwrite($fp, "SET NAMES utf8mb4;\n");
    fwrite($fp, "SET FOREIGN_KEY_CHECKS = 0;\n\n");

    $tables = ['users', 'product', 'product_images', 'receipts', 'issues', 'borrow_records', 'audit_logs', 'app_settings'];

    foreach ($tables as $table) {
        if (!inventory_table_exists($db, $table)) {
            continue;
        }

        fwrite($fp, "-- --------------------------------------------------------\n");
        fwrite($fp, "-- Table structure for `{$table}`\n");
        fwrite($fp, "-- --------------------------------------------------------\n");
        fwrite($fp, "DROP TABLE IF EXISTS `{$table}`;\n");

        $createStmt = $db->query('SHOW CREATE TABLE `' . $table . '`')->fetch();
        $createSql = $createStmt['Create Table'] ?? '';
        fwrite($fp, $createSql . ";\n\n");

        fwrite($fp, "-- Dumping data for `{$table}`\n");
        $rows = $db->query('SELECT * FROM `' . $table . '`')->fetchAll();
        if ($rows !== []) {
            $columnNames = array_keys($rows[0]);
            $colList = implode(', ', array_map(static fn($c) => '`' . $c . '`', $columnNames));

            foreach ($rows as $row) {
                $values = [];
                foreach ($columnNames as $col) {
                    $val = $row[$col];
                    if ($val === null) {
                        $values[] = 'NULL';
                    } elseif ($table === 'product_images' && $col === 'data') {
                        $values[] = '0x' . bin2hex((string) $val);
                    } else {
                        $values[] = $db->quote((string) $val);
                    }
                }
                fwrite($fp, "INSERT INTO `{$table}` ({$colList}) VALUES (" . implode(', ', $values) . ");\n");
            }
        }
        fwrite($fp, "\n");
    }

    fwrite($fp, "SET FOREIGN_KEY_CHECKS = 1;\n");
    fwrite($fp, "-- End of backup\n");
    fclose($fp);

    return filesize($outputPath) ?: 0;
}

